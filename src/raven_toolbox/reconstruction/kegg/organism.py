"""Build a draft model for a KEGG species from the reference artefacts.

Ports the **organism-ID** path of RAVEN ``getKEGGModelForOrganism`` (the branch
taken when no FASTA file is given). An organism already annotated in KEGG needs no
homology search: the function takes the gene and KO assignments of the organism, maps
KOs to reactions against the gene-free reference model, OR-joins the organism's genes
into each reaction's GPR, and keeps the reactions that have genes (and optionally
spontaneous reactions). The HMM and FASTA path is in :mod:`.query`.

Consumes the reference artefacts: the gene-free reference ``cobra.Model`` plus the
``ko_reaction``, ``organism_gene_ko`` and ``rxn_flags`` tables. The mapping of KOs
to reactions comes from the ``ko_reaction`` table, so it does not depend on KEGG
annotations of the reference model surviving an SBML round trip.

Domain mode (``organism_id`` ``"eukaryotes"`` or ``"prokaryotes"``) keeps the genes
of every organism in that domain; it needs the KEGG ``taxonomy`` file. Unlike
RAVEN, it uses the domain classification directly and does not compute the
``getPhylDist`` distance matrix, which RAVEN uses for per-organism HMM
subsampling; the fixed prok90 and euk90 libraries need no subsampling.
"""
from __future__ import annotations

from pathlib import Path

import cobra
import pandas as pd

from raven_toolbox.io.yaml import read_yaml_model
from raven_toolbox.reconstruction.kegg.assemble import _DOMAINS, assemble_model_from_ko_genes
from raven_toolbox.reconstruction.kegg.parse import _resolve_artefact, read_kegg_table
from raven_toolbox.reconstruction.kegg.taxonomy import organisms_in_domain

_NOTE = "Included by get_kegg_model_for_organism (no HMMs)"


def get_kegg_model_for_organism(
    organism_id: str,
    reference_model: cobra.Model,
    ko_reaction: pd.DataFrame,
    organism_gene_ko: pd.DataFrame,
    *,
    rxn_flags: pd.DataFrame | None = None,
    taxonomy: str | Path | None = None,
    keep_spontaneous: bool = True,
    keep_undefined_stoich: bool = True,
    keep_incomplete: bool = True,
    keep_general: bool = False,
) -> cobra.Model:
    """Reconstruct a draft model for a KEGG species from its KO annotations.

    Parameters
    ----------
    organism_id
        Three- or four-letter KEGG organism code (for example ``"eco"``), or
        ``"eukaryotes"`` or ``"prokaryotes"`` for a whole-domain model (requires
        ``taxonomy``). Matched case-insensitively.
    reference_model
        The gene-free KEGG reference model (from :func:`build_reference_model`).
    ko_reaction, organism_gene_ko, rxn_flags
        The relational tables from :func:`build_kegg_tables` (or read back with
        :func:`read_kegg_table`).
    taxonomy
        Path to the KEGG ``taxonomy`` file; required in domain mode.
    keep_spontaneous, keep_undefined_stoich, keep_incomplete, keep_general
        Quality filters (RAVEN's ``keep*``). A reaction flagged in ``rxn_flags``
        is dropped unless its keep flag is set; this takes precedence over having
        genes. Spontaneous reactions without genes are also kept when
        ``keep_spontaneous`` is true.

    Returns
    -------
    cobra.Model
        A copy of the reference restricted to the organism's reactions, with GPRs
        built and ``kegg.genes`` annotations on the genes.
    """
    org = organism_id.lower()
    if org in _DOMAINS:
        if taxonomy is None:
            raise ValueError(
                f"Domain mode ({organism_id!r}) needs the KEGG taxonomy file; "
                "pass taxonomy=."
            )
        members = organisms_in_domain(taxonomy, org)
        rows = organism_gene_ko[organism_gene_ko["organism"].str.lower().isin(members)]
    else:
        known = set(organism_gene_ko["organism"].str.lower())
        if org not in known:
            raise ValueError(
                f"Organism '{organism_id}' has no genes in organism_gene_ko. "
                f"Provide a KEGG species code present in the table."
            )
        rows = organism_gene_ko[organism_gene_ko["organism"].str.lower() == org]

    ko_to_genes: dict[str, list[str]] = {}
    for org_code, gene, ko in zip(rows["organism"], rows["gene"], rows["ko"], strict=True):
        # In domain mode genes from different organisms can share a bare id;
        # qualify with the organism so they stay distinct.
        gene_id = gene if org not in _DOMAINS else f"{org_code.lower()}:{gene}"
        ko_to_genes.setdefault(ko, []).append(gene_id)

    model, _ = assemble_model_from_ko_genes(
        reference_model,
        ko_reaction,
        ko_to_genes,
        rxn_flags=rxn_flags,
        keep_spontaneous=keep_spontaneous,
        keep_undefined_stoich=keep_undefined_stoich,
        keep_incomplete=keep_incomplete,
        keep_general=keep_general,
        model_id=organism_id,
        model_name=f"Generated by get_kegg_model_for_organism for {organism_id}",
        note=_NOTE,
    )
    for gene in model.genes:
        # Species mode: bare gene id -> organism:gene. Domain mode: already
        # organism-qualified.
        value = gene.id if ":" in gene.id else f"{org}:{gene.id}"
        gene.annotation["kegg.genes"] = value
    return model


def get_kegg_model_for_organism_from_artefacts(
    organism_id: str,
    artefact_dir: str | Path | None = None,
    *,
    version: str | None = None,
    taxonomy: str | Path | None = None,
    **kwargs,
) -> cobra.Model:
    """Load the published reference artefacts from ``artefact_dir`` and build the model.

    Reads ``reference_model.yml.gz`` and the gzipped TSV tables ``ko_reaction``,
    ``organism_gene_ko`` and ``rxn_flags``, then calls :func:`get_kegg_model_for_organism`.
    If ``artefact_dir`` is ``None``, the published artefacts are fetched and cached via
    :func:`raven_toolbox.data.ensure_kegg_data` (``version`` selects the release).
    Remaining keyword arguments go to :func:`get_kegg_model_for_organism`.

    For a whole-domain model (``organism_id`` ``"prokaryotes"`` or ``"eukaryotes"``)
    the KEGG ``taxonomy`` artefact is taken from ``artefact_dir`` if present, otherwise
    fetched via :func:`raven_toolbox.data.ensure_kegg_taxonomy`, because it is a separate
    artefact outside the core set. An explicit ``taxonomy`` path takes precedence.
    """
    if artefact_dir is None:
        from raven_toolbox.data import ensure_kegg_data

        artefact_dir = ensure_kegg_data(version=version)
    artefact_dir = Path(artefact_dir)
    if taxonomy is None and organism_id.lower() in _DOMAINS:
        try:
            taxonomy = _resolve_artefact(artefact_dir, "taxonomy.gz")
        except FileNotFoundError:
            from raven_toolbox.data import ensure_kegg_taxonomy

            taxonomy = ensure_kegg_taxonomy(version=version)
    reference_model = read_yaml_model(_resolve_artefact(artefact_dir, "reference_model.yml.gz"))
    ko_reaction = read_kegg_table(_resolve_artefact(artefact_dir, "ko_reaction.tsv.gz"))
    organism_gene_ko = read_kegg_table(_resolve_artefact(artefact_dir, "organism_gene_ko.tsv.gz"))
    rxn_flags = read_kegg_table(_resolve_artefact(artefact_dir, "rxn_flags.tsv.gz"))
    return get_kegg_model_for_organism(
        organism_id,
        reference_model,
        ko_reaction,
        organism_gene_ko,
        rxn_flags=rxn_flags,
        taxonomy=taxonomy,
        **kwargs,
    )
